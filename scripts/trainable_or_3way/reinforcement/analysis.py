def fit_source(a, e, labels, *, source, dataset, split):
    require(source==dataset and split=="dev", "M5/M6 may fit ONLY source dev")
    a,e,y=np.asarray(a),np.asarray(e),np.asarray(labels)
    require(a.shape==e.shape==y.shape and a.ndim==1 and set(y.tolist())=={0,1}, "Source dev needs both classes")
    require(np.isfinite(a).all() and np.isfinite(e).all() and ((a>=0)&(a<=1)&(e>=0)&(e<=1)).all(),
            "Invalid source fitting scores")
    x=design(a,e)
    prior=np.array([1.,0.,0.])
    def objective(w):
        z=x@w
        return float(np.mean(np.logaddexp(0,z)-y*z)+.005*np.sum((w-prior)**2))
    def gradient(w):
        return x.T@(expit(x@w)-y)/len(y)+.01*(w-prior)
    result=minimize(objective,prior,jac=gradient,method="L-BFGS-B",
                    options=dict(maxiter=1000,ftol=1e-12,gtol=1e-9))
    require(result.success and np.isfinite(result.x).all(), "Source-dev calibration failed: "+str(result.message))
    return dict(format="trainable_final_score_v1",weights=result.x.tolist(),emotion_used=True,
                epsilon=EPSILON,regularization=.01,threshold=.5,prior=prior.tolist(),split="dev",
                source=source,dataset=dataset,label="clip_label",class_weight=None,n=len(y),
                objective=float(result.fun),iterations=int(result.nit),success=True)

def csv_text(rows):
    stream=io.StringIO(newline="")
    if rows:
        writer=csv.DictWriter(stream,fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    return stream.getvalue()

def strata(y, modality_labels, probabilities):
    v,a=modality_labels.T
    masks=dict(both_real=(v==0)&(a==0),video_only_fake=(v==1)&(a==0),
               audio_only_fake=(v==0)&(a==1),both_fake=(v==1)&(a==1),
               unknown_modality=(v<0)|(a<0))
    return {k:dict(n=int(mask.sum()),metrics=metric_table(y[mask],{m:p[mask] for m,p in probabilities.items()}) if mask.any() else {})
            for k,mask in masks.items()}

def figures(folder,y,p):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from sklearn.metrics import roc_curve
    fig,axes=plt.subplots(1,2,figsize=(12,4.5))
    for key,score in p.items():
        if len(np.unique(y))==2:
            fpr,tpr,_=roc_curve(y,score)
            axes[0].plot(fpr,tpr,label=key,linewidth=1.1)
    axes[0].plot([0,1],[0,1],color="gray",linestyle="--")
    axes[0].set(xlabel="Real FPR",ylabel="Fake recall",title="ROC (fixed saved scores)")
    axes[0].legend(fontsize=8)
    for key,color in (("M0","tab:blue"),("M1","tab:orange"),("M4","tab:green")):
        for label,style in ((0,"-"),(1,"--")):
            if (y==label).any():
                axes[1].hist(p[key][y==label],bins=np.linspace(0,1,41),density=True,histtype="step",
                             color=color,linestyle=style,label=key+(" Real" if label==0 else " Fake"))
    axes[1].set(xlabel="Fake score",ylabel="Density",title="Score distribution")
    axes[1].legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(folder/"curves.png",dpi=180)
    plt.close(fig)

def fit_all(output, inventory, original, spec, identity):
    folder=Path(output)/"p1"
    lock_path=folder/"FITTED_MODELS.json"
    dev_keys=sorted(k for k,c in inventory["cohorts"].items() if c["split"]=="dev")
    fitting_identity=digest(dict(run=identity,dev={k:inventory["cohorts"][k]["normalized_sha256"] for k in dev_keys},
                                spec=spec,original=original))
    if lock_path.exists() and (folder/"fit/COMPLETED.json").exists():
        saved=read(lock_path)
        require(saved["identity"]==fitting_identity, "Source calibration lock changed")
        require(saved["payload_sha256"]==digest(saved["models"]), "Source calibration coefficients changed")
        # Results generated by this fitting stage have a separate immutable completion receipt.
        require(completed(folder/"fit",fitting_identity), "Missing source calibration completion receipt")
        receipt=read(folder/"fit/COMPLETED.json")
        require(receipt["model_sha256"]==sha(lock_path), "Source fusion lock changed")
        return saved["models"]
    # A lock without its receipt is an interrupted uncommitted fit; refit source dev only.
    models={k:dict(v) for k,v in original.items()}
    for key in dev_keys:
        c=inventory["cohorts"][key]
        require(c["source"]==c["target"], "Calibration dataset differs from source")
        d=load_npz(Path(output)/"p0"/c["normalized_file"])
        old=models[c["source"]+"__"+c["condition"]]
        p,valid=scores(d["raw"],old)
        for m,column in (("M5",2),("M6",3)):
            print(f"[P1 FIT] {key} {m} source-dev only n={int(valid.sum())}",flush=True)
            old[m]=fit_source(p["M0"][valid],d["raw"][valid,column],d["labels"][valid,0],
                              source=c["source"],dataset=c["target"],split=c["split"])
    # Commit coefficients before opening any target/test arrays.
    atomic_json(lock_path,dict(identity=fitting_identity,models=models,payload_sha256=digest(models),
                              target_used_for_fitting=False,independent_calibration=False))
    atomic_json(folder/"fit/COMPLETED.json",dict(identity=fitting_identity,files={},model_sha256=sha(lock_path)))
    return models

def execute(config,output,run_identity):
    out=Path(output)
    p0=out/"p0"
    require(completed(p0,digest(dict(run=run_identity,stage="p0"))), "Run p0 successfully first")
    verify_preserved(out)
    spec,inventory,original=(read(p0/n) for n in ("ANALYSIS_SPEC.json","INVENTORY.json","MODELS.json"))
    identity=digest(dict(run=run_identity,stage="p1",p0=sha(p0/"COMPLETED.json")))
    folder=out/"p1"
    if completed(folder,identity):
        print("[P1] COMPLETE verified; nothing to repeat",flush=True)
        return
    models=fit_all(out,inventory,original,spec,identity)
    summary,job_files=[],[]
    targets=[(k,c) for k,c in sorted(inventory["cohorts"].items()) if c["split"]=="test"]
    progress=Progress("P1 jobs",len(targets)*2,folder)
    failures=[]
    for target_no,(key,c) in enumerate(targets):
        d=load_npz(p0/c["normalized_file"])
        p,valid=scores(d["raw"],models[c["source"]+"__"+c["condition"]])
        for ci,cohort in enumerate(("full","common_emotion")):
            job=folder/key/cohort
            job_identity=digest(dict(run=identity,input=c["normalized_sha256"],models=models[c["source"]+"__"+c["condition"]],
                                     cohort=cohort,bootstrap=spec["bootstrap"]))
            if completed(job,job_identity):
                print("[P1] REUSE "+key+"/"+cohort,flush=True)
                report=read(job/"METRICS.json")
                boot=read(job/"BOOTSTRAP.json")
            else:
                mask=np.ones(len(valid),bool) if cohort=="full" else valid
                require(mask.any(), "No samples in "+key+"/"+cohort)
                probabilities={k:v[mask].copy() for k,v in p.items()}
                if cohort=="full":
                    # Pure M2/M3 raw scores stay NaN in P0; full-cohort policies are explicit.
                    for m in ("M2","M3"):
                        probabilities[m][~valid]=p["M1"][~valid]
                y=d["labels"][mask,0]
                report=dict(source=c["source"],target=c["target"],condition=c["condition"],cohort=cohort,
                            n=len(y),groups=len(set(d["cluster"][mask])),missing_emotion=int((~valid[mask]).sum()),
                            metrics=metric_table(y,probabilities),threshold=.5,
                            full_M2_M3_label="Emotion/Hierarchical OR + artifact-affine missing fallback" if cohort=="full" else None)
                atomic_json(job/"METRICS.json",report)
                atomic_json(job/"STRATA.json",strata(y,d["labels"][mask,1:],probabilities))
                atomic_json(job/"PAIRED_ERRORS.json",paired_changes(y,probabilities,d["sample_id"][mask]))
                rows=[dict(sample_id=str(s),cluster=str(g),clip_label=int(label),emotion_complete=bool(v),
                           **{m:float(probabilities[m][i]) for m in METHODS})
                      for i,(s,g,label,v) in enumerate(zip(d["sample_id"][mask],d["cluster"][mask],y,valid[mask]))]
                atomic_text(job/"predictions.csv",csv_text(rows))
                figures(job,y,probabilities)
                if set(y.tolist())=={0,1} and len(set(d["cluster"][mask]))>1:
                    stable_seed=(config["seed"]+int(digest(key+"/"+cohort)[:8],16))%(2**32)
                    boot=bootstrap(y,probabilities,d["cluster"][mask],job,job_identity,
                        replicates=config["bootstrap"],seed=stable_seed,max_attempts=config["max_attempts"],
                        checkpoint_every=config["checkpoint_every"])
                else:
                    boot=dict(status="INSUFFICIENT_CLASSES_OR_CLUSTERS",comparisons={})
                atomic_json(job/"BOOTSTRAP.json",boot)
                # A limited/failed bootstrap is explicitly recorded, never reported as successful analysis.
                files=["METRICS.json","STRATA.json","PAIRED_ERRORS.json","predictions.csv","curves.png","BOOTSTRAP.json"]
                if (job/"bootstrap_state.npz").exists():
                    files.append("bootstrap_state.npz")
                finish(job,job_identity,files)
            if boot["status"]!="COMPLETE":
                failures.append(key+"/"+cohort+": "+boot["status"])
            for m,v in report["metrics"].items():
                summary.append(dict(source=c["source"],target=c["target"],condition=c["condition"],cohort=cohort,
                         method=m,name=METHODS[m]+(" + missing fallback" if cohort=="full" and m in ("M2","M3") else ""),
                         **{k:v[k] for k in ("n","real","fake","roc_auc","fake_f1","real_fpr","fake_recall",
                                            "balanced_accuracy","macro_f1","average_precision","all_fake_f1")}))
            for pth in job.iterdir():
                if pth.is_file() and pth.name not in ("progress.json",) and not pth.name.endswith(".partial"):
                    job_files.append(pth.relative_to(folder).as_posix())
            progress.update(target_no*2+ci+1,detail=key+"/"+cohort,force=True)
    atomic_text(folder/"SUMMARY.csv",csv_text(summary))
    atomic_json(folder/"SUMMARY.json",dict(rows=summary,primary_family_complete=False,bootstrap_limitations=failures))
    lines=["# P1 saved-score reinforcement analysis","",
           "Historical FAV is separate from B/C. P2 common-condition bidirectional evaluation remains pending.",
           "All metrics below use threshold 0.5. M5/M6 were fitted only on complete source-dev rows.",
           "Full-cohort M2/M3/M4/M5/M6 use the same artifact-affine missing fallback; common_emotion excludes the same IDs for every method.",
           "Targets were already observed. Dev was reused for model selection and fitting.",
           "Bootstrap describes fixed-model/cohort uncertainty, not retraining variability. FAV Real n=60 remains a small denominator.",
           "Paired changes/errors and modality strata are saved per job; examples are the first 10 IDs in lexical order in each error category.",
           "95% and 98.75% intervals are in BOOTSTRAP.json. Only M4-M1 cross B/C AUC belongs to the planned four-comparison primary family; that family is incomplete.","",
           "| Source | Target | Condition | Cohort | Method | ROC-AUC % | Fake F1 % | Real FPR % | Fake Recall % |",
           "|---|---|---|---|---|---:|---:|---:|---:|"]
    def fmt(v):
        return "--" if v is None else f"{100*v:.4f}"
    for r in summary:
        lines.append("| "+" | ".join([r["source"],r["target"],r["condition"],r["cohort"],r["name"]]+
                     [fmt(r[k]) for k in ("roc_auc","fake_f1","real_fpr","fake_recall")])+" |")
    if failures:
        lines += ["","Bootstrap limitations:"]+["- "+s for s in failures]
    atomic_text(folder/"REPORT.md","\n".join(lines)+"\n")
    verify_preserved(out)
    if failures:
        atomic_json(folder/"LIMITATIONS.json",dict(status="ANALYSIS_LIMITED",issues=failures))
        raise RuntimeError("Some bootstrap jobs could not produce the requested valid replicates; see p1/SUMMARY.json")
    finish(folder,identity,sorted(set(job_files+["FITTED_MODELS.json","fit/COMPLETED.json","SUMMARY.csv","SUMMARY.json","REPORT.md"])))
    print("[P1] COMPLETE; see "+str(folder/"REPORT.md"),flush=True)
